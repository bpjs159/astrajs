/** Resuelve la etiqueta de un link del config pre-built (footer y categorías). */
export function navKey(href: string): string {
  const staticMap: Record<string, string> = {
    '/': 'nav.home',
    '/blog': 'nav.blog',
    '/about': 'nav.about',
    '/contact': 'nav.contact',
  };
  if (staticMap[href]) return staticMap[href]!;
  const catMatch = /^\/categories\/([\w-]+)$/.exec(href);
  if (catMatch) return `cat.${catMatch[1]}`;
  // Los nombres de autores son nombres propios: se pasan tal cual
  // (t() devuelve la clave si no existe, así que el nombre se conserva).
  const authorMatch = /^\/authors\/([\w-]+)$/.exec(href);
  if (authorMatch) {
    const author = db.findAuthor(authorMatch[1]!);
    return author?.name ?? href;
  }
  return href;
}
