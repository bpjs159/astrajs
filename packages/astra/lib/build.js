/**
 * astra build — production build with deployment adapters.
 *
 * Pipeline:
 *   1. vite build                      → client bundle + manifests (dist/)
 *   2. dist/astra-server-modules.json  → handler id → defining module map
 *   3. .astra/server-entry.ts          → imports the real handler modules
 *                                         (closures with module scope) plus
 *                                         the adapter shell
 *   4. vite build --ssr                → single-file server bundle
 *   5. adapter emitter                 → platform files:
 *                                         node       dist/server/server.mjs + Dockerfile
 *                                         vercel     api/astra.mjs + vercel.json
 *                                         cloudflare dist/_worker.js + wrangler.toml
 */
